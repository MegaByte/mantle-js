// genWarmLikelihood -- bake recorded shader usage into src/renderer/warmLikelihood.js: for each fill variant key, in how many of the recorded games it
// was linked and drawn.
//
//   node scripts/genWarmLikelihood.mjs <usage-dir> [out.js]
//
// <usage-dir> holds census-<game>.json files (one shader-usage recording per game: rows[0].progFacts = { id, defines }, startupDraws / activeDraws keyed by
// program id). A key is the program's define list, sorted and joined with '|' (the renderer's variant key). The table stores a 32-bit FNV hash of the key
// (the file stays small and carries no program source), plus per-token and per-feature-family counts for keys no recording saw.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node scripts/genWarmLikelihood.mjs <usage-dir> [out.js]');
  process.exit(2);
}
const out =
  process.argv[3] ||
  path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/renderer/warmLikelihood.js');
const FNV = (s) => {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619) >>> 0;
  return h.toString(16);
};
const VERT_ONLY = new Set(['MANTLE_IS_LB_VERT', 'MANTLE_COVER_KID_SRC']);
const FAMILIES = ['GRADIENT', 'CLIP', 'MASK', 'FILTER', 'STROKE', 'PATTERN', 'IMAGE', 'RECOLOR'];
const readRow = (f) => {
  try {
    const r = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')).rows[0];
    return r && r.progFacts ? r : null;
  } catch {
    return null;
  }
}; // (a file still being written has no row)
const files = fs
  .readdirSync(dir)
  .filter((f) => /^census-.*\.json$/.test(f) && readRow(f))
  .sort();
const keys = new Map(),
  tokens = new Map(),
  uses = new Map();
const bump = (m, k, i) => {
  let a = m.get(k);
  if (!a) m.set(k, (a = [0, 0]));
  a[i]++;
};
for (const f of files) {
  const r = readRow(f);
  const drawn = new Set([
    ...Object.keys(r.startupDraws || {}),
    ...Object.keys(r.activeDraws || {}),
  ]);
  const lk = new Set(),
    dr = new Set();
  // fill variants only: ds.variantKeys is the renderer's variant cache. A program's recorded defines also carry the vertex-stage defines the program builder adds.
  const fill = new Set(((r.ds && r.ds.variantKeys) || []).map((v) => v.key));
  for (const p of r.progFacts || []) {
    if (!p.defines || !p.defines.length) continue;
    const k = p.defines
      .filter((d) => !VERT_ONLY.has(d))
      .sort()
      .join('|');
    if (!fill.has(k)) continue;
    lk.add(k);
    if (drawn.has(String(p.id))) dr.add(k);
  }
  const perGame = (set, i) => {
    const t = new Set(),
      u = new Set();
    for (const k of set) {
      bump(keys, FNV(k), i);
      for (const d of k.split('|')) t.add(d);
      for (const fam of FAMILIES) if (!k.includes('MANTLE_NO_' + fam)) u.add(fam);
    }
    for (const d of t) bump(tokens, d, i);
    for (const d of u) bump(uses, d, i);
  };
  perGame(lk, 1);
  perGame(dr, 0);
}
const obj = (m) => Object.fromEntries([...m.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1)));
const body = `// SPDX-FileCopyrightText: 2026 Aaron Kaluszka
// SPDX-License-Identifier: Apache-2.0

// GENERATED by scripts/genWarmLikelihood.mjs from recorded shader usage: do not edit.
// For each fill variant key (FNV-1a of the sorted define list): [games that drew it, games that linked it] out of \`games\`. \`tokens\` the same per define,
// \`uses\` per feature family for keys that do NOT omit the family (a key without MANTLE_NO_GRADIENT uses gradients).
export const WARM_LIKELIHOOD = ${JSON.stringify({ version: 1, games: files.length, keys: obj(keys), tokens: obj(tokens), uses: obj(uses) })};
`;
fs.writeFileSync(out, body);
console.log(
  `${files.length} games, ${keys.size} keys, ${tokens.size} tokens -> ${out} (${body.length} bytes)`,
);
