import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import path from 'path';
const D = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'renderer') + '/';
// Every module that reads/writes R (keep in sync with the contract-smoke
// MODULES list + renderer.js). A stale list drops members used only across the
// newer modules — e.g. _autoNodeClip / _recordBundleDraw — breaking check:types.
const mods = [
  'renderer',
  'shaderPrograms',
  'drawImages',
  'instancedFill',
  'morphDraw',
  'drawSprites',
  'cacheDraw',
  'staticCache',
  'filterDraw',
  'clipDraw',
  'bundleHandle',
  'maskBake',
  'fillPass',
  'frameLoop',
  'drawDispatch',
  'incrementalStroke',
  'aacPointsDraw',
  'glState',
  'rowEngines',
  'routeBytes',
  'viewCull',
  'opaquePrepass',
  'unifiedFillDraw',
  'gpuGate',
  'warmManifest',
];
const all = mods.map((m) => readFileSync(D + m + '.js', 'utf8')).join('\n');
const strip = (s) => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/\/\/[^\n]*/g, ' ');
const src = strip(all);
const mem = new Set();
// reads + R.x = writes
for (const m of src.matchAll(/\bR\.(\w+)\b/g)) mem.add(m[1]);
// brace-matched extraction of a { } block starting at index i (i points at '{')
function block(s, i) {
  let d = 0;
  for (let j = i; j < s.length; j++) {
    if (s[j] === '{') d++;
    else if (s[j] === '}') {
      d--;
      if (!d) return s.slice(i + 1, j);
    }
  }
  return '';
}
// top-level keys of an object-literal body: `key:` or shorthand `key,`/`key}`
function keys(body) {
  const k = new Set();
  let d = 0,
    buf = '';
  const flush = () => {
    const t = buf.trim();
    const m = t.match(/^([A-Za-z_$]\w*)\s*[:,]?/);
    if (m && !/^(get|set)$/.test(m[1])) k.add(m[1]);
    buf = '';
  };
  for (const c of body) {
    if ('{[('.includes(c)) d++;
    else if ('}])'.includes(c)) d--;
    if (c === ',' && d === 0) {
      flush();
      continue;
    }
    buf += c;
  }
  flush();
  return k;
}
// Destructured context reads are members too (including optional legacy cleanup).
for (const m of src.matchAll(/(?:const|let)\s*\{([^}]+)\}\s*=\s*R\b/g))
  for (const item of m[1].split(',')) {
    const n = item.trim().split(/[:=]/)[0].trim();
    if (/^\w+$/.test(n)) mem.add(n);
  }
// const R = { ... }
let i = src.search(/\bconst R\s*=\s*\{/);
if (i >= 0) {
  const b = src.indexOf('{', i);
  for (const k of keys(block(src, b))) mem.add(k);
}
// Object.assign(R, { ... })
for (const m of src.matchAll(/Object\.assign\(R,\s*\{/g)) {
  const b = src.indexOf('{', m.index + m[0].length - 1);
  for (const k of keys(block(src, b))) mem.add(k);
}
// Object.defineProperty(R, 'x'|"x", ...)
for (const m of src.matchAll(/Object\.defineProperty\(R,\s*['"](\w+)['"]/g)) mem.add(m[1]);
const names = [...mem].sort();
const typeOf = (n) =>
  n === 'gl'
    ? 'WebGL2RenderingContext'
    : /Prog$/.test(n) && !/ensure/i.test(n)
      ? 'WebGLProgram'
      : 'any';
const body = names.map((n) => ` * ${n}?: ${typeOf(n)},`).join('\n');
const out = `// Shared renderer context contract. Generated by scripts/genRendererContext.mjs.
// Regenerate when a module adds or removes an R member.
// Members are optional because attach functions initialize the context in stages.
/**
 * @typedef {{
${body}
 * }} RendererContext
 */
export {};
`;
writeFileSync(D + 'rendererContext.js', out);
console.log('members:', names.length);
