// Generate public declarations from JSDoc into types/ using tsconfig.dts.json.
// Renderer type checking runs separately through checkRendererTypes.mjs.
// Resolve TypeScript relative to this package, including hoisted installations.
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PKG = path.resolve(HERE, '..');
const PROJECT = path.join(PKG, 'tsconfig.dts.json');
const OUT = path.join(PKG, 'types');

let tscJs;
try {
  tscJs = createRequire(import.meta.url).resolve('typescript/bin/tsc');
} catch {
  console.error('gen:types: TypeScript not found. Install it: `npm install -D typescript`.');
  process.exit(2);
}

// TypeScript overwrites declarations for live sources but does not remove
// declarations whose source files or exports disappeared. Always build from an
// empty artifact directory so removed APIs cannot leak into the npm package.
rmSync(OUT, { recursive: true, force: true });
const r = spawnSync(process.execPath, [tscJs, '-p', PROJECT], { cwd: PKG, encoding: 'utf8' });
// noEmitOnError is false, so declarations emit even if TS reports diagnostics in
// the (ungated) non-renderer JS. Only a HARD failure (config error, no output)
// is fatal here.
const out = (r.stdout || '') + (r.stderr || '');
if ((r.status !== 0 && /error TS5\d{3}/.test(out)) || !existsSync(path.join(OUT, 'index.d.ts'))) {
  // TS5xxx = config/CLI errors (e.g. bad rootDir) — these block emission.
  console.error('gen:types: declaration emit failed:\n' + out.trim());
  process.exit(1);
}
// A banner so a stray types/ directory identifies the build it came from.
{
  const idx = path.join(OUT, 'index.d.ts');
  const version = JSON.parse(readFileSync(path.join(PKG, 'package.json'), 'utf8')).version;
  writeFileSync(
    idx,
    `// @kontek/mantle ${version} public declarations, generated by scripts/genTypes.mjs from the source JSDoc.\n${readFileSync(idx, 'utf8')}`,
  );
}
console.log('gen:types: public-API declarations emitted to types/ (types/index.d.ts).');
process.exit(0);
