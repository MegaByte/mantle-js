// genFeatureEntry.mjs — generate a minimal Mantle entry module from the
// features a set of SVG + font assets actually use.
//
// This closes the feature-splitting loop: featureSet.inspect() reports
// which renderer subsystems each bundle exercises, featureManifest maps
// those to the side-effect module subpaths that register the matching
// handlers, shaderFilesFor maps the same feature union to the assembled
// generated/*.glsl those features need, and this script writes both out as
// a generated `mantle.features.js`. A consuming app imports THAT instead of
// the `@kontek/mantle` barrel; the bundler then sees only the JS subpaths
// AND only the shader files the assets need and drops the rest (the registry
// seam is what gives it something to drop).
//
// One feature resolution drives JS handlers AND shaders: the generated file
// exports `shaderSources` (static, bundler-trimmed+minified) for createRenderer,
// plus a feature-bound `loadShaders(baseUrl)` runtime fallback for no-bundler use.
//
// Usage:
//   node scripts/genFeatureEntry.mjs <assetDir> [--out mantle.features.js]
//
//   <assetDir>   directory scanned recursively for *.svg AND *.ttf/otf/ttc/woff2
//   --out FILE   output path (default: ./mantle.features.js)
//
// Re-run whenever the asset set changes. The header lists the union of
// features found and the file that introduced each, so the output is
// auditable.

import { readFileSync, writeFileSync, readdirSync, statSync } from 'fs';
import { join, relative, resolve } from 'path';
import { DOMParser as DP } from '@xmldom/xmldom';
globalThis.DOMParser = DP;

import importSvg from '../src/svg/importer.js';
import { inspect, toNames } from '../src/bundle/featureSet.js';
import { featuresToModules } from '../src/bundle/featureManifest.js';
import { detectFontModules } from '../src/font/auto.js';
import { shaderFilesFor } from '../src/shaders/index.js';

const PKG = '@kontek/mantle';

function parseArgs(argv) {
  const args = { dir: null, out: 'mantle.features.js' };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--out') args.out = argv[++i];
    else if (!args.dir) args.dir = a;
  }
  if (!args.dir) {
    console.error('usage: genFeatureEntry.mjs <assetDir> [--out mantle.features.js]');
    process.exit(2);
  }
  return args;
}

function* walkExt(dir, re) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) yield* walkExt(p, re);
    else if (re.test(name)) yield p;
  }
}
const walkSvgs = (dir) => walkExt(dir, /\.svg$/i);
const walkFonts = (dir) => walkExt(dir, /\.(ttf|otf|ttc|woff2)$/i);

async function main() {
  const { dir, out } = parseArgs(process.argv.slice(2));
  const absDir = resolve(dir);

  let union = 0n;
  const perAsset = []; // { file, names }
  let count = 0;

  for (const file of walkSvgs(absDir)) {
    count++;
    let flags = 0n;
    try {
      const svgText = readFileSync(file, 'utf8');
      // bundleForm:false → structured object that inspect() can walk.
      const bundle = await importSvg(svgText, { bundleForm: false });
      flags = inspect(bundle);
    } catch (err) {
      console.warn(`! skipped ${relative(absDir, file)}: ${err.message}`);
      continue;
    }
    union |= flags;
    perAsset.push({ file: relative(absDir, file), names: toNames(flags) });
  }

  // Fonts → reader/shaper modules (named registrations, dedup by subpath).
  const fontMods = new Map(); // pkg → register
  const fontAssets = []; // { file, mods }
  let fontCount = 0;
  for (const file of walkFonts(absDir)) {
    fontCount++;
    try {
      const bytes = new Uint8Array(readFileSync(file));
      const { modules: fm } = await detectFontModules(bytes);
      for (const m of fm) fontMods.set(m.pkg, m.register);
      fontAssets.push({ file: relative(absDir, file), mods: fm.map((m) => m.pkg) });
    } catch (err) {
      console.warn(`! skipped ${relative(absDir, file)}: ${err.message}`);
    }
  }
  const fontEntries = [...fontMods].sort((a, b) => (a[0] < b[0] ? -1 : 1));

  const modules = featuresToModules(union);
  const shaderFiles = shaderFilesFor({ features: union }); // [[key, subpath], …]
  const unionNames = toNames(union);

  const lines = [];
  lines.push('// AUTO-GENERATED by scripts/genFeatureEntry.mjs — do not edit.');
  lines.push('//');
  lines.push(`// Source assets: ${count} SVG(s) + ${fontCount} font(s) under ${dir}`);
  lines.push(
    `// SVG features used: ${unionNames.length ? unionNames.join(', ') : '(none beyond core)'}`,
  );
  lines.push(
    `// Font modules used: ${fontEntries.length ? fontEntries.map(([p]) => p).join(', ') : '(none beyond core)'}`,
  );
  lines.push('//');
  lines.push('// Importing this module registers exactly the optional handlers the');
  lines.push('// scanned assets need. Import it ONCE at app startup, before you');
  lines.push('// create a renderer. Re-run the generator when the asset set changes.');
  lines.push('');
  if (modules.length) {
    lines.push('// SVG feature registrations (side-effect imports):');
    for (const m of modules) lines.push(`import '${m}';`);
    lines.push('');
  }
  if (fontEntries.length) {
    lines.push('// Font reader/shaper registrations (named — called below):');
    for (const [pkg, reg] of fontEntries) lines.push(`import { ${reg} } from '${PKG}/${pkg}';`);
    lines.push('');
    for (const [, reg] of fontEntries) lines.push(`${reg}();`);
    lines.push('');
  }
  if (!modules.length && !fontEntries.length) {
    lines.push('// No optional (registry-backed) features used — core renderer covers everything.');
    lines.push('');
  }
  lines.push('// NO `export * from "@kontek/mantle"` here — that root barrel pulls in');
  lines.push('// (and registers) EVERY subsystem, which would defeat the whole point');
  lines.push('// of this file. Import the API you need straight from the divided');
  lines.push('// subpaths (@kontek@kontek/mantle/renderer, /svg, /animation, /scene,');
  lines.push('// /hitTest, /font/text, /textBundle). This module is meant to be');
  lines.push('// imported for its registration SIDE EFFECTS (the imports above) plus');
  lines.push('// the feature-scoped shaderSources / loadShaders below — nothing else.');
  lines.push('');
  // Shaders, resolved from the same feature union as the handler imports
  // above (shaderFilesFor is the shader peer of featuresToModules). Two ways
  // to consume — both already scoped to the asset feature set:
  //
  //   A) STATIC `shaderSources` — the bundler-native path, full parity with
  //      the handler imports above: only these .glsl land in the build and
  //      your glsl-minify plugin minifies them. `?raw` is Vite/esbuild's
  //      "import file as text"; adjust the suffix/loader for your bundler.
  //   B) RUNTIME `loadShaders(baseUrl)` — no bundler needed; fetches the same
  //      feature-scoped set at runtime. Use when you can't (or don't want to)
  //      inline the GLSL at build time.
  lines.push('// (A) Static, feature-scoped shader sources — pass straight to createRenderer:');
  lines.push('//       import { shaderSources } from "./mantle.features.js";');
  lines.push('//       const renderer = createRenderer(gl, shaderSources);');
  lines.push('//     Bundler tree-shakes/minifies these exactly like the handler imports.');
  lines.push('//     `?raw` = import-as-text (Vite/esbuild); adjust for your bundler.');
  if (shaderFiles.length) {
    for (const [key, sub] of shaderFiles)
      lines.push(`import ${key} from '${PKG}/shaders/${sub}?raw';`);
    lines.push(`export const shaderSources = { ${shaderFiles.map(([k]) => k).join(', ')} };`);
  } else {
    lines.push('export const shaderSources = {};');
  }
  lines.push('');
  lines.push('// (B) Runtime fallback (no bundler) — same feature set, fetched at runtime.');
  lines.push('//     Call loadShaders(baseUrl); the feature set is already baked in.');
  lines.push("import { loadShaders as _loadShadersAll } from '@kontek/mantle/shaders';");
  lines.push(`const _MANTLE_FEATURES = ${union.toString()}n;`);
  lines.push('export function loadShaders(baseUrl, spec) {');
  lines.push('  // An explicit spec from the caller still wins (escape hatch); by');
  lines.push('  // default we bind the asset feature set.');
  lines.push('  return _loadShadersAll(baseUrl, spec || { features: _MANTLE_FEATURES });');
  lines.push('}');
  lines.push('');
  // The feature union, and curve typeOmit (per-bundle curve-kernel stripping via segTypeMask).
  // No scene-level fill defines: the fill variants omit a bundle's unused features on their
  // own, and createRenderer's fillDefines is a debug-only test hook, so this
  // file exports no `fillDefines`.
  lines.push('// The asset feature union + curve typeOmit (createRenderer opts):');
  lines.push(`export const mantleFeatures = ${union.toString()}n;`);
  lines.push('export const typeOmit = true;');
  lines.push('');

  const outAbs = resolve(out);
  writeFileSync(outAbs, lines.join('\n'), 'utf8');

  // Console summary.
  console.log(
    `Scanned ${count} SVG(s) (${perAsset.length} clean) + ${fontCount} font(s) (${fontAssets.length} clean).`,
  );
  console.log(`SVG features: ${unionNames.join(', ') || '(none)'}`);
  console.log(`SVG registration modules (${modules.length}):`);
  for (const m of modules) console.log(`  ${m}`);
  console.log(`Font registration modules (${fontEntries.length}):`);
  for (const [pkg, reg] of fontEntries) console.log(`  ${pkg} → ${reg}()`);
  console.log(
    `Feature-scoped shaders (${shaderFiles.length}/${shaderFilesFor(null).length}): ${shaderFiles.map(([k]) => k).join(', ')}`,
  );
  console.log(`Wrote ${outAbs}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
